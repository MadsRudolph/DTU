// node matlab_check.js > check_matlab_lines.m ; matlab -batch check_matlab_lines
// Every MATLAB line on the page (each formula solved for each of its variables) must reproduce
// a consistent sample point computed by the page's own solver.
'use strict';
const { TOPICS, CONSTANTS } = require('./src/formulas.js');
const E = require('./src/engine.js');
const INV = require('./src/inverses.js');
const consts = Object.fromEntries(Object.entries(CONSTANTS).map(([k, v]) => [k, v.value]));
const SAMPLE = { db: 63.7, unit: 0.37, sym: 0.41, ge1: 2.3, deg90: 33, int: 2, any: 47, pos: 1.73 };
const out = ['% generated by matlab_check.js', 'rho = 1.2; c = 343; p0 = 20e-6; I0 = 1e-12; W0 = 1e-12; g = 9.81;', 'NFAIL__ = 0; NCHK__ = 0;'];
for (const T of TOPICS) T.formulas.forEach((F, i) => {
  const lhs = F.vars[0];
  const vals = {};
  F.vars.slice(1).forEach((k, j) => vals[k] = SAMPLE[T.vars[k][3] || 'pos'] * (1 + 0.13 * j));
  if (lhs === 'th') vals.ka = 5.2;
  if (lhs === 'B') vals.fu = 2 * vals.fl;
  if (lhs === 'alpha_s') vals.T2 = 0.6 * vals.T1;
  if (lhs === 'pd') { vals.k = 1.1; vals.d = 0.4; }
  const roots = E.solve1(x => F.f(Object.assign({}, consts, vals, { [lhs]: x })), T.vars[lhs][3]);
  if (!roots.length) { out.push(`% no JS value for ${T.id}/${F.name}`); return; }
  vals[lhs] = roots[0];
  const lines = INV[`${T.id}_${i}`] || {};
  for (const [k, line] of Object.entries(lines)) {
    const want = vals[k];
    out.push(`clear ${F.vars.join(' ')}`);
    Object.entries(vals).filter(([n]) => n !== k).forEach(([n, v]) => out.push(`${n} = ${v};`));
    out.push(`${line.replace('GUESS', String(want * 1.05))};`);
    const label = `${T.id}/${F.name} -> ${k}`.replace(/'/g, "''");
    out.push(`NCHK__ = NCHK__ + 1; if abs(${k} - (${want})) > 1e-6*max(1, abs(${want})), NFAIL__ = NFAIL__ + 1; fprintf('MISMATCH %s: %g vs %g\\n', '${label}', ${k}, ${want}); end`);
  }
});
out.push("fprintf('%d of %d MATLAB lines match\\n', NCHK__ - NFAIL__, NCHK__);");
console.log(out.join('\n'));
