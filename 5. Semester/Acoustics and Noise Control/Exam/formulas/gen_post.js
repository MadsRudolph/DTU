// src/inverses.json (MATLAB symbolic output) -> src/inverses.js: a readable MATLAB line per formula and variable.
'use strict';
const fs = require('fs');
const { TOPICS } = require('./src/formulas.js');
const E = require('./src/engine.js');
const M = require('./mexpr.js');
const raw = JSON.parse(fs.readFileSync(__dirname + '/src/inverses.json', 'utf8'));
const degrees = s => s
  .replace(/\b(sin|cos|tan)\(pi\*(\w+)\/180\)/g, '$1d($2)')
  .replace(/\b(sin|cos|tan)\((\w+)\*pi\/180\)/g, '$1d($2)')
  .replace(/180\*a(sin|cos|tan)\(([^()]*)\)\/pi/g, 'a$1d($2)');
const out = {};
for (const T of TOPICS) T.formulas.forEach((F, i) => {
  const id = `${T.id}_${i}`, e = raw[id] || {}, lines = {};
  for (const k of F.vars) {
    if (T.vars[k][3] === 'int') continue;
    if (k === F.vars[0]) { lines[k] = E.toMatlab(F); continue; }
    if (e[k]) { try { lines[k] = `${k} = ${degrees(M.toMatlab(e[k].replace(/\b(\w+)_v\b/g, '$1')))}`; continue; } catch (err) { console.error('parse', id, k, err.message); } }
    // no closed form: fzero on the formula itself (scalar; GUESS is replaced by a start value)
    const line = E.toMatlab(F), eq = line.indexOf('=');
    const lhs = line.slice(0, eq).trim(), rhs = line.slice(eq + 1).trim();
    lines[k] = `${k} = fzero(@(${k}) ${rhs} - ${lhs}, GUESS)`;
  }
  out[id] = lines;
});
const js = `// generated by gen_post.js from MATLAB's symbolic solve (gen_inverses.js) - do not edit by hand
(function (root) { const INVERSES = ${JSON.stringify(out, null, 1)};
if (typeof module === 'object' && module.exports) module.exports = INVERSES; else root.INVERSES = INVERSES; })(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(__dirname + '/src/inverses.js', js);
const all = Object.values(out).flatMap(o => Object.values(o));
console.log(`${all.length} MATLAB lines, ${all.filter(l => l.includes('fzero')).length} via fzero`);
