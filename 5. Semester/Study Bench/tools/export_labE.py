#!/usr/bin/env python3
"""Lab E measured data -> courses/34870/labE_measured.js (window.LABE_MEAS).

Reads the Group 10 files in the labs repo (5. Semester/Electroacoustics/Labs/Lab E/data/).
Baffle runs: |H| in dB re 1 Pa/V. System runs: |H| per unit at 0 and 30 degrees and the
wrapped 0-degree phase (deg), so the site can do its own phase compensation.
Everything above 18 kHz is dropped: the UMIK channel jumps ~20 dB there in every run."""
import json, pathlib
import numpy as np, scipy.io as sio

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "Electroacoustics/Labs/Lab E/data"
OUT = ROOT / "Study Bench/courses/34870/labE_measured.js"
FMAX = 18000

ld = lambda t: sio.loadmat(DATA / f"labE_{t}.mat", squeeze_me=True)
r1 = lambda v: [round(float(x), 1) for x in v]

out = {}
b = ld("box_0"); k = b["fn"] <= FMAX
out["fb"] = [round(float(x), 1) for x in b["fn"][k]]
for t in ["box_0", "box_30", "circle_0", "circle_30", "iec_0", "iec_15", "iec_30", "iec_60"]:
    out[t] = r1(20 * np.log10(np.abs(ld(t)["H"][k])))
s0, s30 = ld("system_0"), ld("system_30")
k = s0["fn"] <= FMAX
out["fs"] = [round(float(x), 1) for x in s0["fn"][k]]
for u, name in enumerate(["w", "m", "t"]):
    out[f"{name}0"] = r1(20 * np.log10(np.abs(s0["H"][k, u])))
    out[f"{name}30"] = r1(20 * np.log10(np.abs(s30["H"][k, u])))
    out[f"{name}0ph"] = [int(round(x)) for x in np.degrees(np.angle(s0["H"][k, u]))]
out["dims"] = {"r1": 2.44, "a": 0.30, "iec": [0.51, 0.71], "drv": [0.205, 0.44], "as": 0.03, "r2": 2.44, "h2": 1.15, "T": 20}

head = ("// Lab E: measured Tue 20-Oct-2026 (Group 10, System D, UMIK 708-0332), anechoic chamber, mic 2.44 m.\n"
        "// Generated by Study Bench/tools/export_labE.py from Labs/Lab E/data/labE_*.mat. dB re 1 Pa/V, 50 Hz - 18 kHz.\n"
        "// fb/box_*/circle_*/iec_*: 3\" driver, 24/oct. fs/w,m,t: woofer, midrange, tweeter, 48/oct; *0ph = wrapped phase at 0 deg.\n")
OUT.write_text(head + "window.LABE_MEAS = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(OUT, OUT.stat().st_size // 1024, "KB")
